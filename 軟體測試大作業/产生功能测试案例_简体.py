def main():
    out_dir = os.path.dirname(os.path.abspath(__file__))
    cases_dir = os.path.join(out_dir, "功能测试案例_简体")
    os.makedirs(cases_dir, exist_ok=True)
    all_rows = []
    total = 0
    for name, start, cases in modules:
        rows = []
        for i, (method, inp, expect) in enumerate(cases):
            tc = "TC-%03d" % (start + i)
            row = [tc, name, method, inp, expect, "", ""]
            rows.append(row)
            all_rows.append(row)
        total += len(cases)
        fn = os.path.join(cases_dir, "%s.csv" % name)
        with open(fn, "w", newline="", encoding="utf-8-sig") as f:
            w = csv.writer(f)
            w.writerow(HEADER)
            w.writerows(rows)
        print("%-16s %3d 条 -> %s" % (name, len(cases), os.path.basename(fn)))
    allfn = os.path.join(cases_dir, "功能测试案例_全部.csv")
    with open(allfn, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        w.writerows(all_rows)
    print("-" * 40)
    print("合计 %d 条 -> %s" % (total, os.path.basename(allfn)))
